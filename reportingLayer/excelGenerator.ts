
import ExcelJS from 'exceljs';
import { mkdir } from 'node:fs/promises';
import { join } from 'node:path';

import { findMissingReportingFields } from './missingFields';

import {
    styleSummaryLayout,
    styleTitle,
    styleTableHeader,
    styleDataRow,
    styleStatusCell,
    styleSummarySection,
    styleSummaryField,
    styleSummaryResult,
    styleWorksheetTab,
    setColumnWidths,
} from './excelStyles';

interface SchemaField {
    readonly field: string;
    readonly label: string;
    readonly order: number;
}

interface SummarySection {
    readonly section: string;
    readonly order: number;
    readonly fields: readonly SchemaField[];
}

export interface ExcelEvidenceTest {
    readonly testId: string;
    readonly testName: string;
    readonly status: 'passed' | 'failed' | 'notExecuted';
    readonly retry: number;
    readonly annotations: Readonly<Record<string, string>>;
    readonly values: Readonly<Record<string, unknown>>;
}

export interface ExcelGenerationOptions {
    readonly outputDirectory: string;
    readonly project: string;
    readonly product: string;
    readonly evidenceSchema: readonly SchemaField[];
    readonly summarySchema: readonly SummarySection[];
    readonly summaryData: Readonly<Record<string, unknown>>;
    readonly tests: readonly ExcelEvidenceTest[];
}

const NOT_KNOWN = 'Not Known';

/**
 * Runtime metadata generated by EvidenceFactory.
 *
 * These annotations are not business reporting fields
 * and must not appear in Missing Reporting Fields.
 */
const INTERNAL_METADATA_FIELDS = new Set([
    'browserVersion',
    'viewport',
]);

/**
 * Reporter-generated values take priority over
 * annotations for these technical fields.
 *
 * All other fields retain annotation-first behavior.
 */
const REPORTER_FIELDS = new Set([
    'scenarioId',
    'scenarioName',
    'status',
    'retry',
    'attempt',
    'workerId',
    'startTime',
    'endTime',
    'durationMs',
    'error',
    'mode',
    'device',
    'browser',
    'browserChannel',
    'browserVersion',
    'headless',
]);

function excelValue(value: unknown): ExcelJS.CellValue {
    if (value === null || value === undefined) {
        return '';
    }

    if (
        typeof value === 'string' ||
        typeof value === 'number' ||
        typeof value === 'boolean' ||
        value instanceof Date
    ) {
        return value;
    }

    try {
        return JSON.stringify(value) ?? String(value);
    } catch {
        return String(value);
    }
}

function orderedFields(
    fields: readonly SchemaField[],
): SchemaField[] {
    return [...fields].sort((a, b) => a.order - b.order);
}

/**
 * Converts a date to a readable local-time string.
 *
 * Existing date formatting behavior is preserved.
 */
function formatDateTime(value: unknown): string {
    if (value === null || value === undefined || value === '') {
        return NOT_KNOWN;
    }

    const date = value instanceof Date
        ? value
        : new Date(String(value));

    if (Number.isNaN(date.getTime())) {
        return String(value);
    }

    const day = String(date.getDate()).padStart(2, '0');

    const month = [
        'Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun',
        'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec',
    ][date.getMonth()];

    const year = date.getFullYear();

    const hours = String(date.getHours()).padStart(2, '0');
    const minutes = String(date.getMinutes()).padStart(2, '0');
    const seconds = String(date.getSeconds()).padStart(2, '0');

    return (
        `${day}-${month}-${year} ` +
        `${hours}:${minutes}:${seconds}`
    );
}

/**
 * Standard duration format: mm:ss.
 *
 * Numeric input is interpreted as milliseconds.
 * Already-formatted mm:ss values are preserved.
 *
 * Minutes may exceed 59 for long executions.
 */
function formatDuration(value: unknown): string {
    if (typeof value === 'number' && Number.isFinite(value)) {
        const totalSeconds = Math.floor(
            Math.max(0, value) / 1000,
        );

        const minutes = Math.floor(totalSeconds / 60);
        const seconds = totalSeconds % 60;

        return (
            `${String(minutes).padStart(2, '0')}:` +
            `${String(seconds).padStart(2, '0')}`
        );
    }

    if (typeof value === 'string') {
        const text = value.trim();

        if (/^\d+:[0-5]\d$/.test(text)) {
            return text;
        }

        const secondsMatch = text.match(
            /^([\d.]+)\s+seconds?$/i,
        );

        if (secondsMatch) {
            return formatDuration(Number(secondsMatch[1]) * 1000);
        }

        return text || NOT_KNOWN;
    }

    return NOT_KNOWN;
}

function formatSummaryValue(
    field: string,
    value: unknown,
): ExcelJS.CellValue {
    switch (field) {
        case 'startedAt':
        case 'finishedAt':
            return formatDateTime(value);

        case 'executionTime':
            return formatDuration(value);

        case 'headless':
            if (value === true || value === 'true') {
                return 'Yes';
            }

            if (value === false || value === 'false') {
                return 'No';
            }

            return excelValue(value ?? NOT_KNOWN);

        case 'platform':
            if (value === 'win32') return 'Windows';
            if (value === 'darwin') return 'macOS';
            if (value === 'linux') return 'Linux';

            return excelValue(value ?? NOT_KNOWN);

        case 'runId': {
            const text = String(value ?? '');

            if (!text) {
                return NOT_KNOWN;
            }

            return text.startsWith('run-')
                ? text
                : `run-${text}`;
        }

        default:
            return excelValue(value ?? NOT_KNOWN);
    }
}

/**
 * Resolve a detail-cell value.
 *
 * Technical fields come from the reporter.
 * Business evidence fields come from annotations.
 */
function getDetailValue(
    test: ExcelEvidenceTest,
    field: string,
): unknown {
    if (field === 'status') {
        return test.status;
    }

    if (field === 'retry') {
        return test.retry;
    }

    if (REPORTER_FIELDS.has(field)) {
        return test.values[field] ?? NOT_KNOWN;
    }

    if (
        Object.prototype.hasOwnProperty.call(
            test.annotations,
            field,
        )
    ) {
        return test.annotations[field];
    }

    return test.values[field] ?? '';
}

/**
 * SUMMARY WORKSHEET
 */
function createSummarySheet(
    workbook: ExcelJS.Workbook,
    options: ExcelGenerationOptions,
): void {
    const sheet = workbook.addWorksheet('Summary');

    styleSummaryLayout(sheet);

    sheet.getCell('A1').value =
        `Execution Summary  |  Project: ${options.project}` +
        `  |  Product: ${options.product}`;

    styleTitle(sheet, 1, 2);
    styleWorksheetTab(sheet);

    let rowNumber = 3;

    const sections = [...options.summarySchema].sort(
        (a, b) => a.order - b.order,
    );

    for (const section of sections) {
        sheet.getCell(rowNumber, 1).value = section.section;

        styleSummarySection(sheet, rowNumber, 2);
        rowNumber++;

        for (const field of orderedFields(section.fields)) {
            sheet.getCell(rowNumber, 1).value = field.label;

            sheet.getCell(rowNumber, 2).value =
                formatSummaryValue(
                    field.field,
                    options.summaryData[field.field],
                );

            styleSummaryField(sheet, rowNumber, field.field);
            styleSummaryResult(sheet, rowNumber, field.field);

            rowNumber++;
        }

        rowNumber++;
    }
}

/**
 * DETAIL WORKSHEETS
 *
 * All, Passed, Failed, Not Executed
 */
function createDetailSheet(
    workbook: ExcelJS.Workbook,
    sheetName: string,
    tests: readonly ExcelEvidenceTest[],
    evidenceSchema: readonly SchemaField[],
): void {
    const sheet = workbook.addWorksheet(sheetName);
    const fields = orderedFields(evidenceSchema);

    fields.forEach((field, index) => {
        sheet.getCell(1, index + 1).value = field.label;
    });

    styleTableHeader(sheet, 1, fields.length);

    const statusIndex = fields.findIndex(
        field => field.field === 'status',
    );

    tests.forEach((test, index) => {
        const rowNumber = index + 2;

        fields.forEach((field, columnIndex) => {
            const value = getDetailValue(test, field.field);

            sheet.getCell(
                rowNumber,
                columnIndex + 1,
            ).value = excelValue(value);
        });

        styleDataRow(sheet, rowNumber, fields.length);

        if (statusIndex >= 0) {
            styleStatusCell(
                sheet.getCell(rowNumber, statusIndex + 1),
                test.status,
            );
        }
    });

    setColumnWidths(sheet);
}

/**
 * MISSING REPORTING FIELDS WORKSHEET
 *
 * Ignore internal EvidenceFactory metadata while
 * preserving missing business annotation detection.
 */
function createMissingFieldsSheet(
    workbook: ExcelJS.Workbook,
    tests: readonly ExcelEvidenceTest[],
    evidenceSchema: readonly SchemaField[],
): void {
    const missing = findMissingReportingFields(
        tests.map(test => ({
            testName: test.testName,
            annotations: Object.entries(test.annotations)
                .filter(
                    ([type]) => !INTERNAL_METADATA_FIELDS.has(type),
                )
                .map(([type, description]) => ({
                    type,
                    description,
                })),
        })),
        evidenceSchema,
    );

    if (missing.length === 0) {
        return;
    }

    const sheet = workbook.addWorksheet(
        'Missing Reporting Fields',
    );

    const headers = [
        'Missing Field',
        'Affected Tests',
        'Occurrences',
    ];

    headers.forEach((header, index) => {
        sheet.getCell(1, index + 1).value = header;
    });

    styleTableHeader(sheet, 1, headers.length);

    missing.forEach((item, index) => {
        const rowNumber = index + 2;

        sheet.getCell(rowNumber, 1).value = item.field;
        sheet.getCell(rowNumber, 2).value =
            item.affectedTests.join(', ');
        sheet.getCell(rowNumber, 3).value = item.occurrences;

        styleDataRow(sheet, rowNumber, headers.length);
    });

    setColumnWidths(sheet);
}

/**
 * GENERATE EVIDENCE EXCEL
 */
export async function generateEvidenceExcel(
    options: ExcelGenerationOptions,
): Promise<string> {
    await mkdir(options.outputDirectory, {
        recursive: true,
    });

    const workbook = new ExcelJS.Workbook();

    workbook.creator = 'EvidenceFactory';
    workbook.created = new Date();

    createSummarySheet(workbook, options);

    const detailSheets = [
        {
            name: 'All',
            tests: options.tests,
        },
        {
            name: 'Passed',
            tests: options.tests.filter(
                test => test.status === 'passed',
            ),
        },
        {
            name: 'Failed',
            tests: options.tests.filter(
                test => test.status === 'failed',
            ),
        },
        {
            name: 'Not Executed',
            tests: options.tests.filter(
                test => test.status === 'notExecuted',
            ),
        },
    ];

    for (const detail of detailSheets) {
        createDetailSheet(
            workbook,
            detail.name,
            detail.tests,
            options.evidenceSchema,
        );
    }

    createMissingFieldsSheet(
        workbook,
        options.tests,
        options.evidenceSchema,
    );

    const timestamp = new Date()
        .toISOString()
        .replace(/[:.]/g, '-');

    const filePath = join(
        options.outputDirectory,
        `evidence-report-${timestamp}.xlsx`,
    );

    await workbook.xlsx.writeFile(filePath);

    console.log(
        `EvidenceFactory: Excel report generated: ${filePath}`,
    );

    return filePath;
}
